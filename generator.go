const (
	cldrRepoReleasesURL = "https://api.github.com/repos/unicode-org/cldr-json/releases/"
	isoURL              = "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml"
)

// rootLocale is the name of the CLDR root locale in the cldr-json data.
const rootLocale = "und"

type Generator struct {
	CLDRVersion   string
	ISOLastUpdate string
	Currencies    map[string]*CurrencyInfo
	Locales       map[string]*LocaleInfo
	// Parents holds the CLDR parent locales that are not found by removing the last subtag.
	Parents map[string]string
	tempDir string
}

type CurrencyInfo struct {
	Code          string // ISO 4217 code (e.g., "USD")
	Number        string // ISO 4217 number (e.g., "840")
	Name          string // Official currency name
	MinorUnits    int    // Number of decimal places
	CashIncrement int64  // Smallest cash amount in minor units
}

type LocaleInfo struct {
	Numbers Numbers
	// Symbols holds the currency symbols that this locale defines, without inherited symbols.
	Symbols map[string]string
	// CurrencyNumbers holds the number data that this locale defines for one currency, without inherited data.
	CurrencyNumbers map[string]CurrencyNumbers
}

// CurrencyNumbers is the CLDR number data of one currency in a locale. An empty field uses the locale data.
type CurrencyNumbers struct {
	Pattern string
	Decimal string
	Group   string
}

type Numbers struct {
	CurrencyFormat   string // Currency pattern (e.g., "#,##0.00 ¤")
	GroupSeparator   string // Group separator (e.g., "," in en)
	DecimalSeparator string // Decimal separator (e.g., "." in en)
	MinusSign        string // Minus sign (e.g., "-")
	// MinimumGroupingDigits is the smallest number of digits before the first group separator.
	MinimumGroupingDigits int
}

// defaultNumbers is the number data of the zero Locale.
var defaultNumbers = Numbers{
	CurrencyFormat:        "#,##0.00 ¤",
	GroupSeparator:        ",",
	DecimalSeparator:      ".",
	MinusSign:             "-",
	MinimumGroupingDigits: 1,
}

